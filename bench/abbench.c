/* CI-only inflate A/B benchmark (branch inflate-fast-bench, never merged).
 *
 * In process and interleaved: every round decodes every file once per mode, rotating the mode
 * order from round to round, and keeps every time; the tables report the best and the median.
 * Modes: each slz variant of bench/variants.txt (streaming API, with the same memcpy callbacks as
 * tests/bench_inflate.c), "nocopy" = the last variant with a writer that does not copy (cost of
 * the output callback), libdeflate (whole buffer), zlib-ng (native API) and zlib. Streams: zlib
 * level 6, raw deflate, as tests/bench_inflate.c. Every decode is verified outside the timing.
 *
 *   abbench [-r rounds] [-t tag] files... */
#define _POSIX_C_SOURCE 200809L
#include "variants.h" /* generated by bench/run.sh: NV, vname[], vnew[], vdec[] */
#include <libdeflate.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <time.h>
#include <zlib.h>

int zng_decode(const uint8_t *c, size_t cn, uint8_t *o, size_t n, size_t *got); /* zng.c */
const char *zng_ver(void);

static double now(void) {
    struct timespec t;
    clock_gettime(CLOCK_MONOTONIC, &t);
    return (double)t.tv_sec + (double)t.tv_nsec / 1e9;
}

typedef struct {
    const uint8_t *in;
    size_t n, pos;
    uint8_t *out;
    size_t on;
    int nocopy;
} io;
static int64_t rd(void *u, uint8_t *b, size_t n) {
    io *s = (io *)u;
    size_t k = n < s->n - s->pos ? n : s->n - s->pos;
    memcpy(b, s->in + s->pos, k);
    s->pos += k;
    return (int64_t)k;
}
static int wr(void *u, const uint8_t *p, size_t n) {
    io *s = (io *)u;
    if (!s->nocopy) memcpy(s->out + s->on, p, n);
    s->on += n;
    return 0;
}

static uint8_t *readall(const char *path, size_t *n) {
    FILE *f = fopen(path, "rb");
    uint8_t *d;
    long m;
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    m = ftell(f);
    fseek(f, 0, SEEK_SET);
    *n = (size_t)m;
    d = (uint8_t *)malloc(*n + 64);
    if (!d || fread(d, 1, *n, f) != *n) {
        fprintf(stderr, "cannot read %s\n", path);
        exit(2);
    }
    fclose(f);
    return d;
}

typedef struct {
    const char *name;
    uint8_t *d, *c;
    size_t n, cn;
} file;

static void load(file *f, const char *path) {
    const char *b = strrchr(path, '/');
    char cp[1024];
    f->name = b ? b + 1 : path;
    f->d = readall(path, &f->n);
    if (!f->d) {
        fprintf(stderr, "cannot open %s\n", path);
        exit(2);
    }
    snprintf(cp, sizeof cp, "cache/%s.z6", f->name);
    f->c = readall(cp, &f->cn);
    if (!f->c) {
        z_stream zs;
        FILE *o;
        size_t cap = f->n + f->n / 100 + 1024;
        memset(&zs, 0, sizeof zs);
        f->c = (uint8_t *)malloc(cap);
        deflateInit2(&zs, 6, Z_DEFLATED, -15, 8, Z_DEFAULT_STRATEGY);
        zs.next_in = f->d;
        zs.avail_in = (uInt)f->n;
        zs.next_out = f->c;
        zs.avail_out = (uInt)cap;
        if (deflate(&zs, Z_FINISH) != Z_STREAM_END) {
            fprintf(stderr, "deflate %s failed\n", f->name);
            exit(2);
        }
        f->cn = zs.total_out;
        deflateEnd(&zs);
        mkdir("cache", 0755);
        if ((o = fopen(cp, "wb"))) {
            fwrite(f->c, 1, f->cn, o);
            fclose(o);
        }
    }
}

enum { M_VAR, M_NOCOPY, M_LD, M_ZNG, M_ZLIB };
typedef struct {
    const char *name;
    int kind, v;
} mode;

static int cmpd(const void *a, const void *b) {
    double x = *(const double *)a, y = *(const double *)b;
    return x < y ? -1 : x > y;
}

int main(int argc, char **argv) {
    int rounds = 15, nf = 0, nm = 0, a, r, i, k, st;
    const char *tag = "-";
    file *fs = (file *)calloc((size_t)argc, sizeof *fs);
    mode md[NV + 4];
    void *vz[NV];
    struct libdeflate_decompressor *ld = libdeflate_alloc_decompressor();
    size_t maxn = 0, totn = 0;
    double *t, *tmp, tot[2][NV + 4];
    uint8_t *o;
    for (a = 1; a < argc; a++) {
        if (!strcmp(argv[a], "-r") && a + 1 < argc)
            rounds = atoi(argv[++a]);
        else if (!strcmp(argv[a], "-t") && a + 1 < argc)
            tag = argv[++a];
        else {
            load(&fs[nf], argv[a]);
            if (fs[nf].n > maxn) maxn = fs[nf].n;
            totn += fs[nf].n;
            nf++;
        }
    }
    if (!nf || rounds < 1) {
        fprintf(stderr, "usage: abbench [-r rounds] [-t tag] files...\n");
        return 2;
    }
    for (i = 0; i < NV; i++) {
        md[nm].name = vname[i];
        md[nm].kind = M_VAR;
        md[nm++].v = i;
        vz[i] = vnew[i]();
    }
    md[nm].name = "nocopy";
    md[nm].kind = M_NOCOPY;
    md[nm++].v = NV - 1;
    md[nm].name = "libdeflate";
    md[nm++].kind = M_LD;
    md[nm].name = "zlib-ng";
    md[nm++].kind = M_ZNG;
    md[nm].name = "zlib";
    md[nm++].kind = M_ZLIB;
    t = (double *)malloc(sizeof(double) * (size_t)(rounds * nf * nm));
    tmp = (double *)malloc(sizeof(double) * (size_t)rounds);
    o = (uint8_t *)malloc(maxn + 4096);
    for (r = 0; r < rounds; r++) {
        for (i = 0; i < nf; i++) {
            const file *f = &fs[i];
            int j;
            for (j = 0; j < nm; j++) {
                const mode *m = &md[(j + r) % nm];
                size_t got = 0;
                double t0 = 0;
                int rc = 0;
                memset(o, 0, 4096);
                if (m->kind == M_VAR || m->kind == M_NOCOPY) {
                    io s;
                    s.in = f->c;
                    s.n = f->cn;
                    s.pos = 0;
                    s.out = o;
                    s.on = 0;
                    s.nocopy = m->kind == M_NOCOPY;
                    t0 = now();
                    rc = vdec[m->v](vz[m->v], rd, wr, &s);
                    t0 = now() - t0;
                    got = s.on;
                } else if (m->kind == M_LD) {
                    t0 = now();
                    rc = (int)libdeflate_deflate_decompress(ld, f->c, f->cn, o, f->n, &got);
                    t0 = now() - t0;
                } else if (m->kind == M_ZNG) {
                    t0 = now();
                    rc = zng_decode(f->c, f->cn, o, f->n, &got);
                    t0 = now() - t0;
                } else {
                    z_stream zs;
                    memset(&zs, 0, sizeof zs);
                    t0 = now();
                    inflateInit2(&zs, -15);
                    zs.next_in = f->c;
                    zs.avail_in = (uInt)f->cn;
                    zs.next_out = o;
                    zs.avail_out = (uInt)f->n;
                    rc = inflate(&zs, Z_FINISH) != Z_STREAM_END;
                    got = zs.total_out;
                    inflateEnd(&zs);
                    t0 = now() - t0;
                }
                if (rc || got != f->n || (m->kind != M_NOCOPY && memcmp(o, f->d, f->n))) {
                    fprintf(stderr, "MISMATCH mode %s file %s rc %d got %zu want %zu\n", m->name, f->name, rc,
                            got, f->n);
                    return 1;
                }
                t[((size_t)r * (size_t)nf + (size_t)i) * (size_t)nm + (size_t)(m - md)] = t0;
            }
        }
    }
    printf("abbench %s: %d files, %zu bytes, %d rounds; zlib %s, libdeflate %s, zlib-ng %s\n", tag, nf, totn, rounds,
           zlibVersion(), LIBDEFLATE_VERSION_STRING, zng_ver());
    printf("%-10s %10s", "MB/s best", "size");
    for (k = 0; k < nm; k++)
        printf(" %10s", md[k].name);
    printf("\n");
    for (k = 0; k < nm; k++)
        tot[0][k] = tot[1][k] = 0;
    for (i = 0; i < nf; i++) {
        printf("%-10s %10zu", fs[i].name, fs[i].n);
        for (k = 0; k < nm; k++) {
            for (r = 0; r < rounds; r++)
                tmp[r] = t[((size_t)r * (size_t)nf + (size_t)i) * (size_t)nm + (size_t)k];
            qsort(tmp, (size_t)rounds, sizeof *tmp, cmpd);
            tot[0][k] += tmp[0];
            tot[1][k] += rounds & 1 ? tmp[rounds / 2] : (tmp[rounds / 2 - 1] + tmp[rounds / 2]) / 2;
            printf(" %10.0f", (double)fs[i].n / tmp[0] / 1e6);
        }
        printf("\n");
    }
    for (st = 0; st < 2; st++) {
        printf("%-10s %10zu", st ? "TOT median" : "TOTAL best", totn);
        for (k = 0; k < nm; k++)
            printf(" %10.1f", (double)totn / tot[st][k] / 1e6);
        printf("\n");
    }
    for (st = 0; st < 2; st++) {
        printf("ratio %-6s vs %s:", st ? "median" : "best", vname[0]);
        for (k = 1; k < nm; k++)
            printf(" %s %.4f", md[k].name, tot[st][0] / tot[st][k]);
        printf("\n");
        printf("ratio %-6s vs libdeflate:", st ? "median" : "best");
        for (k = 0; k < nm; k++)
            if (md[k].kind != M_LD) printf(" %s %.4f", md[k].name, tot[st][NV + 1] / tot[st][k]);
        printf("\n");
    }
    for (st = 0; st < 2; st++) {
        printf("RESULT tag=%s stat=%s", tag, st ? "median" : "best");
        for (k = 0; k < nm; k++)
            printf(" %s=%.1f", md[k].name, (double)totn / tot[st][k] / 1e6);
        printf("\n");
    }
    return 0;
}
