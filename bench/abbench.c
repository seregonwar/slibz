/* CI-only LZMA2 A/B benchmark (branch lzma2-decode-bench, never merged).
 *
 * In process and interleaved: every round decodes every file once per mode, rotating the mode
 * order from round to round, and keeps every time; the tables report the best and the median.
 * Modes: each slz variant of bench/variants.txt (streaming API, a new decoder per stream and the
 * same memcpy callbacks as tests/bench_lzma.c), "nocopy" = the last variant with a writer that
 * does not copy (cost of the output callback), xz = liblzma lzma_raw_buffer_decode (as
 * tests/bench_lzma.c) and sdk = 7-Zip's C Lzma2Decode (decodes straight into the output buffer).
 * Streams: raw LZMA2, liblzma preset 6 (8 MiB dictionary), as tests/bench_lzma.c. Every decode is
 * verified outside the timing.
 *
 *   abbench [-r rounds] [-t tag] [-m mode] files...   (-m: run only that mode, for profiling) */
#define _POSIX_C_SOURCE 200809L
#include "variants.h" /* generated by bench/run.sh: NV, vname[], vdec[] */
#include <lzma.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <time.h>

int sdk_decode(const unsigned char *c, size_t cn, unsigned char *o, size_t n, unsigned prop, size_t *got);

static double now(void) {
    struct timespec t;
    clock_gettime(CLOCK_MONOTONIC, &t);
    return (double)t.tv_sec + (double)t.tv_nsec / 1e9;
}

typedef struct {
    const uint8_t *in;
    size_t n, pos;
    uint8_t *out;
    size_t on;
    int nocopy;
} io;
static int64_t rd(void *u, uint8_t *b, size_t n) {
    io *s = (io *)u;
    size_t k = n < s->n - s->pos ? n : s->n - s->pos;
    memcpy(b, s->in + s->pos, k);
    s->pos += k;
    return (int64_t)k;
}
static int wr(void *u, const uint8_t *p, size_t n) {
    io *s = (io *)u;
    if (!s->nocopy) memcpy(s->out + s->on, p, n);
    s->on += n;
    return 0;
}

static uint8_t *readall(const char *path, size_t *n) {
    FILE *f = fopen(path, "rb");
    uint8_t *d;
    long m;
    if (!f) return NULL;
    fseek(f, 0, SEEK_END);
    m = ftell(f);
    fseek(f, 0, SEEK_SET);
    *n = (size_t)m;
    d = (uint8_t *)malloc(*n + 64);
    if (!d || fread(d, 1, *n, f) != *n) {
        fprintf(stderr, "cannot read %s\n", path);
        exit(2);
    }
    fclose(f);
    return d;
}

typedef struct {
    const char *name;
    uint8_t *d, *c;
    size_t n, cn;
} file;

static lzma_options_lzma opt;
static lzma_filter flt[2];

static void load(file *f, const char *path) {
    const char *b = strrchr(path, '/');
    char cp[1024];
    f->name = b ? b + 1 : path;
    f->d = readall(path, &f->n);
    if (!f->d) {
        fprintf(stderr, "cannot open %s\n", path);
        exit(2);
    }
    snprintf(cp, sizeof cp, "cache/%s.lzma2-6", f->name);
    f->c = readall(cp, &f->cn);
    if (!f->c) {
        FILE *o;
        size_t cap = f->n + f->n / 10 + 4096;
        f->c = (uint8_t *)malloc(cap);
        f->cn = 0;
        if (lzma_raw_buffer_encode(flt, NULL, f->d, f->n, f->c, &f->cn, cap) != LZMA_OK) {
            fprintf(stderr, "lzma encode %s failed\n", f->name);
            exit(2);
        }
        mkdir("cache", 0755);
        if ((o = fopen(cp, "wb"))) {
            fwrite(f->c, 1, f->cn, o);
            fclose(o);
        }
    }
}

enum { M_VAR, M_NOCOPY, M_XZ, M_SDK };
typedef struct {
    const char *name;
    int kind, v;
} mode;

static int cmpd(const void *a, const void *b) {
    double x = *(const double *)a, y = *(const double *)b;
    return x < y ? -1 : x > y;
}

int main(int argc, char **argv) {
    int rounds = 5, nf = 0, nm = 0, a, r, i, k, st;
    unsigned prop = 0;
    const char *tag = "-", *only = NULL;
    file *fs = (file *)calloc((size_t)argc, sizeof *fs);
    mode md[NV + 3];
    size_t maxn = 0, totn = 0, totc = 0;
    double *t, *tmp, tot[2][NV + 3];
    uint8_t *o;
    lzma_lzma_preset(&opt, 6);
    flt[0].id = LZMA_FILTER_LZMA2;
    flt[0].options = &opt;
    flt[1].id = LZMA_VLI_UNKNOWN;
    while (prop < 40 && ((uint64_t)(2 | (prop & 1)) << (prop / 2 + 11)) < opt.dict_size)
        prop++;
    for (a = 1; a < argc; a++) {
        if (!strcmp(argv[a], "-r") && a + 1 < argc)
            rounds = atoi(argv[++a]);
        else if (!strcmp(argv[a], "-t") && a + 1 < argc)
            tag = argv[++a];
        else if (!strcmp(argv[a], "-m") && a + 1 < argc)
            only = argv[++a];
        else {
            load(&fs[nf], argv[a]);
            if (fs[nf].n > maxn) maxn = fs[nf].n;
            totn += fs[nf].n;
            totc += fs[nf].cn;
            nf++;
        }
    }
    if (!nf || rounds < 1) {
        fprintf(stderr, "usage: abbench [-r rounds] [-t tag] [-m mode] files...\n");
        return 2;
    }
    for (i = 0; i < NV; i++) {
        md[nm].name = vname[i];
        md[nm].kind = M_VAR;
        md[nm++].v = i;
    }
    md[nm].name = "nocopy";
    md[nm].kind = M_NOCOPY;
    md[nm++].v = NV - 1;
    md[nm].name = "xz";
    md[nm++].kind = M_XZ;
    md[nm].name = "sdk";
    md[nm++].kind = M_SDK;
    if (only) {
        for (k = 0; k < nm && strcmp(md[k].name, only); k++)
            ;
        if (k == nm) {
            fprintf(stderr, "unknown mode %s\n", only);
            return 2;
        }
        md[0] = md[k];
        nm = 1;
    }
    t = (double *)malloc(sizeof(double) * (size_t)(rounds * nf * nm));
    tmp = (double *)malloc(sizeof(double) * (size_t)rounds);
    o = (uint8_t *)malloc(maxn + 4096);
    for (r = 0; r < rounds; r++) {
        for (i = 0; i < nf; i++) {
            const file *f = &fs[i];
            int j;
            for (j = 0; j < nm; j++) {
                const mode *m = &md[(j + r) % nm];
                size_t got = 0;
                double t0 = 0;
                int rc = 0;
                memset(o, 0, 4096);
                if (m->kind == M_VAR || m->kind == M_NOCOPY) {
                    io s;
                    s.in = f->c;
                    s.n = f->cn;
                    s.pos = 0;
                    s.out = o;
                    s.on = 0;
                    s.nocopy = m->kind == M_NOCOPY;
                    t0 = now();
                    rc = vdec[m->v](opt.dict_size, f->n, rd, wr, &s);
                    t0 = now() - t0;
                    got = s.on;
                } else if (m->kind == M_XZ) {
                    size_t ip = 0;
                    t0 = now();
                    rc = lzma_raw_buffer_decode(flt, NULL, f->c, &ip, f->cn, o, &got, f->n) != LZMA_OK || ip != f->cn;
                    t0 = now() - t0;
                } else {
                    t0 = now();
                    rc = sdk_decode(f->c, f->cn, o, f->n, prop, &got);
                    t0 = now() - t0;
                }
                if (rc || got != f->n || (m->kind != M_NOCOPY && memcmp(o, f->d, f->n))) {
                    fprintf(stderr, "MISMATCH mode %s file %s rc %d got %zu want %zu\n", m->name, f->name, rc,
                            got, f->n);
                    return 1;
                }
                t[((size_t)r * (size_t)nf + (size_t)i) * (size_t)nm + (size_t)(m - md)] = t0;
            }
        }
    }
    printf("abbench %s: %d files, %zu bytes (LZMA2 preset 6: %zu), %d rounds; liblzma %s, 7-Zip C LzmaDec 26.06\n",
           tag, nf, totn, totc, rounds, lzma_version_string());
    printf("%-10s %10s", "MB/s best", "size");
    for (k = 0; k < nm; k++)
        printf(" %8s", md[k].name);
    printf("\n");
    for (k = 0; k < nm; k++)
        tot[0][k] = tot[1][k] = 0;
    for (i = 0; i < nf; i++) {
        printf("%-10s %10zu", fs[i].name, fs[i].n);
        for (k = 0; k < nm; k++) {
            for (r = 0; r < rounds; r++)
                tmp[r] = t[((size_t)r * (size_t)nf + (size_t)i) * (size_t)nm + (size_t)k];
            qsort(tmp, (size_t)rounds, sizeof *tmp, cmpd);
            tot[0][k] += tmp[0];
            tot[1][k] += rounds & 1 ? tmp[rounds / 2] : (tmp[rounds / 2 - 1] + tmp[rounds / 2]) / 2;
            printf(" %8.1f", (double)fs[i].n / tmp[0] / 1e6);
        }
        printf("\n");
    }
    for (st = 0; st < 2; st++) {
        printf("%-10s %10zu", st ? "TOT median" : "TOTAL best", totn);
        for (k = 0; k < nm; k++)
            printf(" %8.1f", (double)totn / tot[st][k] / 1e6);
        printf("\n");
    }
    for (st = 0; st < 2 && !only; st++) {
        printf("ratio %-6s vs %s:", st ? "median" : "best", vname[0]);
        for (k = 1; k < nm; k++)
            printf(" %s %.4f", md[k].name, tot[st][0] / tot[st][k]);
        printf("\n");
        printf("ratio %-6s vs xz:", st ? "median" : "best");
        for (k = 0; k < nm; k++)
            if (md[k].kind != M_XZ) printf(" %s %.4f", md[k].name, tot[st][NV + 1] / tot[st][k]);
        printf("\n");
    }
    for (st = 0; st < 2; st++) {
        printf("RESULT tag=%s stat=%s", tag, st ? "median" : "best");
        for (k = 0; k < nm; k++)
            printf(" %s=%.1f", md[k].name, (double)totn / tot[st][k] / 1e6);
        printf("\n");
    }
    return 0;
}
